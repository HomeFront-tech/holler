import AppKit
import ApplicationServices

private final class PastePromise: NSObject, NSPasteboardItemDataProvider {
    let text: String
    let supplied: () -> Void
    init(text: String, supplied: @escaping () -> Void) { self.text = text; self.supplied = supplied }
    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        item.setString(text, forType: type)
        // A lazy promise confirms the consumer requested the text, unlike a fixed sleep.
        DispatchQueue.main.async(execute: supplied)
    }
}
final class Inserter {
    private(set) var lastText = ""
    private var promise: PastePromise?
    private var snapshot: [[NSPasteboard.PasteboardType: Data]] = []
    private var ownedChange = -1
    private var generation = 0
    private var landed = false
    private var completion: ((Bool) -> Void)?
    var busy: Bool { promise != nil || completion != nil }
    func remember(_ text: String) { if !text.isEmpty { lastText = text } }
    func paste(_ text: String, target: CaretTarget, completion: @escaping (Bool) -> Void) {
        guard !text.isEmpty, !busy else { completion(false); return }
        lastText = text; self.completion = completion
        generation += 1; let gen = generation
        waitForRelease(text, target: target, deadline: Date().addingTimeInterval(1), gen: gen)
    }
    private func waitForRelease(_ text: String, target: CaretTarget, deadline: Date, gen: Int) {
        guard generation == gen else { return }
        let modifiers: CGEventFlags = [.maskCommand, .maskControl, .maskAlternate, .maskShift, .maskSecondaryFn]
        if !CGEventSource.flagsState(.hidSystemState).intersection(modifiers).isEmpty {
            if Date() >= deadline { complete(false); return }
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.015) { self.waitForRelease(text, target: target, deadline: deadline, gen: gen) }
            return
        }
        guard Caret.stillFocused(target) else { complete(false); return }
        let current = Caret.capture()
        let prefix = Spacing.prefix(value: current.value, caretUTF16: current.location)
        beginPaste(prefix + text, target: target, gen: gen)
    }
    private func beginPaste(_ text: String, target: CaretTarget, gen: Int) {
        let board = NSPasteboard.general
        var total = 0
        snapshot = (board.pasteboardItems ?? []).map { item in
            var contents: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                guard let data = item.data(forType: type), total + data.count <= 20 * 1024 * 1024 else {
                    Log.event("clipboard type skipped: unavailable or over 20 MB"); continue
                }
                total += data.count; contents[type] = data
            }
            return contents
        }
        let item = NSPasteboardItem()
        landed = false
        let promise = PastePromise(text: text) { [weak self] in
            guard let self, self.generation == gen, !self.landed else { return }
            self.landed = true; self.complete(true)
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) {
                if self.generation == gen { self.restore() }
            }
        }
        self.promise = promise
        item.setDataProvider(promise, forTypes: [.string])
        for type in ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"] {
            item.setData(Data(), forType: NSPasteboard.PasteboardType(type))
        }
        board.clearContents()
        guard board.writeObjects([item]) else { ownedChange = board.changeCount; restore(); complete(false); return }
        ownedChange = board.changeCount
        let source = CGEventSource(stateID: .privateState)
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: false) else { restore(); complete(false); return }
        guard Caret.stillFocused(target) else { restore(); complete(false); return }
        down.flags = .maskCommand; up.flags = .maskCommand
        // Tag our own keystrokes so Holler's event tap lets them straight through (e.g. while the physical V of
        // Cmd+Ctrl+V is still down and its key code is on the swallow list).
        down.setIntegerValueField(.eventSourceUserData, value: Hotkeys.syntheticTag)
        up.setIntegerValueField(.eventSourceUserData, value: Hotkeys.syntheticTag)
        down.post(tap: .cghidEventTap); up.post(tap: .cghidEventTap)
        DispatchQueue.main.asyncAfter(deadline: .now() + 1) {
            guard self.generation == gen, !self.landed else { return }
            self.restore(); self.complete(false)
        }
    }
    private func complete(_ success: Bool) {
        let callback = completion; completion = nil
        Log.event(success ? "paste requested by consumer" : "paste failed or focus changed")
        callback?(success)
    }
    private func restore() {
        let board = NSPasteboard.general
        // Never overwrite a copy the user made while dictation was landing.
        if board.changeCount == ownedChange {
            let items = snapshot.filter { !$0.isEmpty }.map { types -> NSPasteboardItem in
                let item = NSPasteboardItem()
                for (type, data) in types { item.setData(data, forType: type) }
                return item
            }
            board.clearContents(); if !items.isEmpty { board.writeObjects(items) }
        }
        snapshot.removeAll(); promise = nil; ownedChange = -1
    }
    func cancel() { generation += 1; restore(); if completion != nil { complete(false) } }
}
